export const getTranslation = (lang: AppLanguage | string, key: string): string => {
  const selectedLang = (lang === 'te' || lang === 'hi' || lang === 'en') ? lang : 'en';
  return TRANSLATIONS[selectedLang]?.[key] || TRANSLATIONS.en[key] || key;
};

export const getCategoryName = (slug: string, fallbackName: string, lang: AppLanguage | string): string => {
  const keyMap: Record<string, string> = {
    'electrician': 'cat_electrician',
    'plumber': 'cat_plumber',
    'kirana': 'cat_kirana',
    'ac-repair': 'cat_ac_repair',
    'mechanic': 'cat_mechanic',
    'veg-cook': 'cat_veg_cook',
    'non-veg-cook': 'cat_non_veg_cook',
    'carpenter': 'cat_carpenter',
    'painter': 'cat_painter',
    'home-tutor': 'cat_home_tutor',
    'barber': 'cat_barber',
    'taxi-auto': 'cat_taxi_auto',
  };

  const key = keyMap[slug];
  if (!key) return fallbackName;
  const translation = getTranslation(lang, key);
  return translation !== key ? translation : fallbackName;
};
